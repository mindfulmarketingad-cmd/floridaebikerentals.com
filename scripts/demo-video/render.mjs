/**
 * Renders the "How Rent Now works" demo video shown on /rent/.
 * Each frame is drawn from scene.html at a fixed time and captured with
 * Playwright, then ffmpeg encodes the frames to MP4 plus a poster image.
 *   node scripts/demo-video/render.mjs
 * Needs Playwright (devDependency) and an ffmpeg binary on PATH or in $FFMPEG.
 */
import { chromium } from "playwright";
import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { bikeIcon } from "../../src/bike-icons.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const FPS = 24;
const DURATION = 22;
const W = 1280, H = 720;
const ffmpeg = process.env.FFMPEG || "ffmpeg";

const html = readFileSync(path.join(here, "scene.html"), "utf8")
  .replace(/<!--bike:([a-z-]+)-->/g, (_, style) => bikeIcon(style));

const frames = path.join(tmpdir(), "fer-demo-frames");
rmSync(frames, { recursive: true, force: true });
mkdirSync(frames, { recursive: true });

const browser = await chromium.launch(process.env.CHROMIUM ? { executablePath: process.env.CHROMIUM } : {});
const page = await browser.newPage({ viewport: { width: W, height: H } });
await page.setContent(html);
const total = FPS * DURATION;
for (let i = 0; i < total; i++) {
  await page.evaluate((t) => window.render(t), i / FPS);
  await page.screenshot({ path: path.join(frames, `f${String(i).padStart(4, "0")}.png`) });
}
await page.evaluate(() => window.render(2.4));
await page.screenshot({ path: path.join(frames, "poster.png") });
await browser.close();

const out = path.join(root, "assets/video");
mkdirSync(out, { recursive: true });
execFileSync(ffmpeg, [
  "-y", "-loglevel", "error", "-framerate", String(FPS), "-i", path.join(frames, "f%04d.png"),
  "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "26", "-preset", "slow", "-movflags", "+faststart",
  "-an", path.join(out, "how-rent-now-works.mp4"),
]);
execFileSync(ffmpeg, ["-y", "-loglevel", "error", "-i", path.join(frames, "poster.png"), "-q:v", "4",
  path.join(out, "how-rent-now-works.jpg")]);
rmSync(frames, { recursive: true, force: true });
writeFileSync(path.join(out, "README.txt"), "Generated by scripts/demo-video/render.mjs. Edit scene.html and re-run it.\n");
console.log("wrote assets/video/how-rent-now-works.mp4 and .jpg");
